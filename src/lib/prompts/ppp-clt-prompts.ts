import { StudentProfile, BlockLesson } from '../../types/lesson-template'

// ─── PPP Lesson Prompt ──────────────────────────────────────────────────────

export function buildPPPLessonPrompt(
  student: StudentProfile,
  lesson: BlockLesson,
  duration: 25 | 50,
  levelGuide: string,
  cefrVocabGuide: string,
  vocabularyContextSection: string
): string {
  const is50min = duration === 50
  const presTime = is50min ? 15 : 10
  const practTime = is50min ? 20 : 10
  const prodTime = is50min ? 10 : 5
  const hwTime = is50min ? 5 : 2

  const lines: string[] = [
    `You are an expert language instructor creating a PPP (Presentation, Practice, Production) lesson.`,
    ``,
    `STUDENT PROFILE:`,
    `- Name: ${student.name}`,
    `- Level: ${student.level}`,
    `- Age: ${student.ageGroup}`,
    `- Goals: ${student.endGoals}`,
    `- Target Language: ${student.targetLanguage}`,
    ``,
    `LESSON:`,
    `- Title: ${lesson.title}`,
    `- Communicative Need: ${lesson.communicativeNeed}`,
    `- Key Language Features: ${lesson.keyLanguageFeatures.join(', ')}`,
    vocabularyContextSection,
    ``,
    `GLOBAL FORMATTING RULES:`,
    `- NEVER use em dashes (—)`,
    `- ALL text content MUST be in ${student.targetLanguage}. JSON keys stay in English.`,
    `- BANNED words: "resonate", "navigate", "landscape", "leverage", "dynamics", "paradigm"`,
    ``,
    `PPP LESSON STRUCTURE (${duration} minutes):`,
    `Exercise 1: Presentation (${presTime} min)`,
    `Exercise 2: Practice (${practTime} min)`,
    `Exercise 3: Production (${prodTime} min)`,
    `Exercise 4: Homework (${hwTime} min)`,
    ``,
    `---`,
    ``,
    `**Exercise 1: Presentation** (${presTime} min)`,
    `Purpose: Introduce target grammar/structure with examples and concept checks.`,
    `- State the target structure clearly`,
    `- Give 3-4 examples in context, relevant to ${student.interests || 'everyday life'}`,
    `- Include 2-3 CCQs that confirm understanding WITHOUT using the target structure`,
    `- ${levelGuide}`,
    ``,
    `Format:`,
    `{`,
    `  "type": "presentation",`,
    `  "title": "[the phrase for 'Grammar Focus' in ${student.targetLanguage}]",`,
    `  "content": {`,
    `    "targetStructure": "[name of structure, in ${student.targetLanguage}]",`,
    `    "explanation": "[clear explanation in ${student.targetLanguage}]",`,
    `    "examples": [`,
    `      { "sentence": "[example in ${student.targetLanguage}]", "note": "[optional note, in ${student.targetLanguage}]" }`,
    `    ],`,
    `    "conceptCheckQuestions": ["[CCQ1 in ${student.targetLanguage}]", "[CCQ2]", "[CCQ3]"]`,
    `  },`,
    `  "timeMinutes": ${presTime}`,
    `}`,
    ``,
    `---`,
    ``,
    `**Exercise 2: Practice** (${practTime} min)`,
    `Purpose: Controlled practice to build accuracy.`,
    `- Mix 2 exercise types: gap-fill, sentence transformation, matching, or word reorder`,
    `- 4-6 items per exercise type; one correct answer only`,
    `- ${cefrVocabGuide}`,
    ``,
    `Format:`,
    `{`,
    `  "type": "practice",`,
    `  "title": "[the phrase for 'Practice Exercises' in ${student.targetLanguage}]",`,
    `  "content": {`,
    `    "instructions": "[overall instructions in ${student.targetLanguage}]",`,
    `    "exercises": [`,
    `      {`,
    `        "type": "gap-fill",`,
    `        "items": [`,
    `          { "id": 1, "prompt": "[sentence with _____ in ${student.targetLanguage}]", "answer": "[correct answer]", "hint": "[grammar hint]" }`,
    `        ]`,
    `      },`,
    `      {`,
    `        "type": "transformation",`,
    `        "items": [`,
    `          { "id": 1, "prompt": "[original sentence + instruction in ${student.targetLanguage}]", "answer": "[transformed sentence]" }`,
    `        ]`,
    `      }`,
    `    ]`,
    `  },`,
    `  "timeMinutes": ${practTime}`,
    `}`,
    ``,
    `---`,
    ``,
    `**Exercise 3: Production** (${prodTime} min)`,
    `Purpose: Student uses the target structure freely in a real communicative context.`,
    ``,
    `Format:`,
    `{`,
    `  "type": "production",`,
    `  "title": "[the phrase for 'Speaking Task' in ${student.targetLanguage}]",`,
    `  "content": {`,
    `    "scenario": "[short context in ${student.targetLanguage}]",`,
    `    "task": "[what student must do, action verb, in ${student.targetLanguage}]",`,
    `    "targetStructure": "[remind student what to use, in ${student.targetLanguage}]",`,
    `    "prompts": ["[optional sentence starter 1 in ${student.targetLanguage}]", "[starter 2]"]`,
    `  },`,
    `  "timeMinutes": ${prodTime}`,
    `}`,
    ``,
    `---`,
    ``,
    `**Exercise 4: Homework** (${hwTime} min)`,
    `Format:`,
    `{`,
    `  "type": "homework",`,
    `  "title": "[the word for 'Homework' in ${student.targetLanguage}]",`,
    `  "content": {`,
    `    "taskName": "[short name in ${student.targetLanguage}]",`,
    `    "description": "[what to do and why, in ${student.targetLanguage}]",`,
    `    "instructions": "[step-by-step, in ${student.targetLanguage}]"`,
    `  },`,
    `  "timeMinutes": ${hwTime}`,
    `}`,
    ``,
    `---`,
    ``,
    `JSON OUTPUT:`,
    `{`,
    `  "title": "${lesson.title}",`,
    `  "lessonType": "grammar",`,
    `  "objective": "[By the end of this lesson, you'll be able to ${lesson.communicativeNeed} — MAX 120 chars, in ${student.targetLanguage}]",`,
    `  "difficulty": ${student.level === 'beginner' ? 3 : student.level === 'elementary' ? 4 : student.level === 'intermediate' ? 6 : 8},`,
    `  "duration": ${duration},`,
    `  "skills": ["Grammar", "Speaking", "Writing"],`,
    `  "vocabulary": [],`,
    `  "context": "${lesson.communicativeNeed}",`,
    `  "exercises": [/* 4 exercises in order */],`,
    `  "homework": "",`,
    `  "materials": [],`,
    `  "teachingNotes": "[tutor notes in ${student.targetLanguage}]"`,
    `}`,
    ``,
    `RETURN ONLY VALID JSON, NO EXPLANATION.`,
  ]

  return lines.join('\n')
}

// ─── CLT Lesson Prompt ──────────────────────────────────────────────────────

export function buildCLTLessonPrompt(
  student: StudentProfile,
  lesson: BlockLesson,
  duration: 25 | 50,
  levelGuide: string,
  cefrVocabGuide: string,
  vocabularyContextSection: string
): string {
  const is50min = duration === 50
  const isKid = ['child', 'kid', 'under 12', 'under 18', 'teen'].some(k =>
    student.ageGroup.toLowerCase().includes(k)
  )

  const inputTime = is50min ? 15 : 10
  const activityTime = is50min ? 20 : 8
  const wrapTime = is50min ? 10 : 2

  const youngLearnerRules = isKid
    ? [
        ``,
        `YOUNG LEARNER RULES:`,
        `- Simple, fun, age-appropriate language`,
        `- Relatable topics (hobbies, school, family, games, animals, travel)`,
        `- Activities should feel like games, not formal exercises`,
        `- Very clear, simple instructions`,
        `- Teach through examples and play, not abstract rules`,
      ]
    : []

  const lines: string[] = [
    `You are an expert language instructor creating a CLT (Communicative Language Teaching) lesson.`,
    ``,
    `STUDENT PROFILE:`,
    `- Name: ${student.name}`,
    `- Level: ${student.level}`,
    `- Age: ${student.ageGroup}`,
    `- Goals: ${student.endGoals}`,
    `- Interests: ${student.interests || 'general topics'}`,
    `- Target Language: ${student.targetLanguage}`,
    ``,
    `LESSON:`,
    `- Title: ${lesson.title}`,
    `- Communicative Need: ${lesson.communicativeNeed}`,
    `- Key Language Features: ${lesson.keyLanguageFeatures.join(', ')}`,
    vocabularyContextSection,
    ``,
    `GLOBAL FORMATTING RULES:`,
    `- NEVER use em dashes (—)`,
    `- ALL text content MUST be in ${student.targetLanguage}. JSON keys stay in English.`,
    `- BANNED words: "resonate", "navigate", "landscape", "leverage", "dynamics", "paradigm"`,
    ...youngLearnerRules,
    ``,
    `CLT LESSON STRUCTURE (${duration} minutes):`,
    `Exercise 1: Warmer (5 min)`,
    `Exercise 2: Language Input (${inputTime} min)`,
    `Exercise 3: Communicative Activity (${activityTime} min)`,
    `Exercise 4: Wrap-up & Homework (${wrapTime} min)`,
    ``,
    `---`,
    ``,
    `**Exercise 1: Warmer** (5 min)`,
    `Purpose: Get student speaking immediately. Fun, low-pressure.`,
    `- Types: quick-fire questions, word association, "would you rather", picture description, 20 questions`,
    isKid ? `- Make it feel like a game` : `- Keep it purposeful and relevant to the lesson topic`,
    ``,
    `CRITICAL WARMER RULES:`,
    `- "instructions" = what the TUTOR says/does to introduce the activity. This is a TUTOR-ONLY note, NOT shown on the student sheet.`,
    `- "prompts" = the actual questions or cues the student responds to. These ARE shown to the student.`,
    `- NEVER address the student by name anywhere in this exercise.`,
    `- NEVER write instructions as if they appear on a student worksheet.`,
    `- "prompts" must invite immediate personal responses — stories, opinions, quick reactions. NEVER analytical questions like "How can X impact Y?", "Why is X important?", "What are the implications of X?" — those belong in a discussion exercise, not a warmer.`,
    ``,
    `Format:`,
    `{`,
    `  "type": "warmer",`,
    `  "title": "[MUST be the word for 'Warm-up' in ${student.targetLanguage} — e.g. 'Warm-up', 'Calentamiento', 'Échauffement']",`,
    `  "content": {`,
    `    "activity": "[activity type in ${student.targetLanguage}]",`,
    `    "instructions": "[TUTOR SETUP: what you say/do to introduce the activity — not shown to student]",`,
    `    "prompts": ["[prompt 1 in ${student.targetLanguage}]", "[prompt 2]", "[prompt 3]"]`,
    `  },`,
    `  "timeMinutes": 5`,
    `}`,
    ``,
    `---`,
    ``,
    `**Exercise 2: Language Input** (${inputTime} min)`,
    `Purpose: Introduce vocabulary IN CONTEXT — not isolated lists.`,
    `- 4-6 single words, level-appropriate`,
    `- ${cefrVocabGuide}`,
    `- ${levelGuide}`,
    `- Always include a short contextual dialogue (2-4 characters, 4-8 lines) that uses the vocabulary naturally`,
    ``,
    `CRITICAL LANGUAGE INPUT RULES:`,
    `- title MUST be the generic word for "Vocabulary" in ${student.targetLanguage} — NOT a topic-specific label like "Invitation Words"`,
    `- contextDialogue: each line needs "speaker" (character name), "gender" ("male"/"female"/"narrator"), and "text"`,
    `- Use ${isKid ? 'simple, child-friendly' : 'realistic'} character names`,
    `- NEVER address the student by name in this exercise`,
    ``,
    `Format:`,
    `{`,
    `  "type": "language-input",`,
    `  "title": "[the word for 'Vocabulary' in ${student.targetLanguage}]",`,
    `  "content": {`,
    `    "vocabulary": [`,
    `      { "word": "[word]", "partOfSpeech": "[in ${student.targetLanguage}]", "phonetics": "/fəˈnetɪks/", "definition": "[in ${student.targetLanguage}]", "example": "[in ${student.targetLanguage}]", "synonym": "[or empty]" }`,
    `    ],`,
    `    "contextDialogue": [`,
    `      { "speaker": "[name]", "gender": "male", "text": "[line in ${student.targetLanguage}]" },`,
    `      { "speaker": "[name]", "gender": "female", "text": "[line in ${student.targetLanguage}]" }`,
    `    ]`,
    `  },`,
    `  "timeMinutes": ${inputTime}`,
    `}`,
    ``,
    `---`,
    ``,
    `**Exercise 3: Communicative Activity** (${activityTime} min)`,
    `Purpose: Student communicates freely. Meaning over perfection.`,
    `- Types: roleplay, information gap, storytelling, opinion sharing, describe-and-guess, interview`,
    isKid ? `- Make it playful — turn it into a game if possible` : `- Keep it purposeful and relevant to real communication needs`,
    ``,
    `CRITICAL COMMUNICATIVE ACTIVITY RULES:`,
    `- "instructions" = TUTOR SETUP ONLY — what you say to introduce the activity. NOT shown on the student sheet. Do NOT address the student by name here.`,
    `- "studentCharacter" = a fictional character name the student plays (e.g., "Alex", "Sam"). NEVER use the student's real name.`,
    `- "studentRole" = the student's task/character brief, written in ${student.targetLanguage}. Say "You are [character]..." or just describe the role. NO real names.`,
    `- "prompts" = task cues shown to the student. NEVER say "me", "I", or the student's real name. Refer to the tutor as "the tutor" if needed.`,
    `- "tutorRole" = tutor-only note, hidden from student`,
    ``,
    `Format:`,
    `{`,
    `  "type": "communicative-activity",`,
    `  "title": "[brief activity label in ${student.targetLanguage}, e.g. 'Speaking Activity', 'Roleplay', 'Information Gap' — NOT a topic-specific name]",`,
    `  "content": {`,
    `    "activityName": "[activity name in ${student.targetLanguage}]",`,
    `    "instructions": "[TUTOR SETUP: how you introduce and run this activity — NOT shown to student]",`,
    `    "studentCharacter": "[fictional character name, e.g. Alex]",`,
    `    "studentRole": "[student's character brief in ${student.targetLanguage} — no real names]",`,
    `    "tutorRole": "[how tutor participates, in ${student.targetLanguage}]",`,
    `    "prompts": ["[cue 1 in ${student.targetLanguage} — no 'me'/'I']", "[cue 2]"]`,
    `  },`,
    `  "timeMinutes": ${activityTime}`,
    `}`,
    ``,
    `---`,
    ``,
    `**Exercise 4: Wrap-up & Homework** (${wrapTime} min)`,
    `CRITICAL WRAP-UP RULES:`,
    `- reviewQuestions are prompts for the TUTOR to ask orally. Write them as plain questions — NEVER address the student by name, NEVER say "you" as if reading from a sheet.`,
    `- Example good: "How do you accept an invitation politely?" Bad: "${student.name}, how do you say yes to an invitation?"`,
    ``,
    `Format:`,
    `{`,
    `  "type": "wrap-up",`,
    `  "title": "[MUST be the phrase for 'Review & Homework' in ${student.targetLanguage}]",`,
    `  "content": {`,
    `    "reviewQuestions": ["[plain review question in ${student.targetLanguage}]", "[Q2]"],`,
    `    "homework": "[specific homework task in ${student.targetLanguage}]"`,
    `  },`,
    `  "timeMinutes": ${wrapTime}`,
    `}`,
    ``,
    `---`,
    ``,
    `JSON OUTPUT:`,
    `{`,
    `  "title": "${lesson.title}",`,
    `  "lessonType": "conversation",`,
    `  "objective": "[By the end of this lesson, you'll be able to ${lesson.communicativeNeed} — MAX 120 chars, in ${student.targetLanguage}]",`,
    `  "difficulty": ${student.level === 'beginner' ? 3 : student.level === 'elementary' ? 4 : student.level === 'intermediate' ? 6 : 8},`,
    `  "duration": ${duration},`,
    `  "skills": ["Speaking", "Listening", "Vocabulary"],`,
    `  "vocabulary": [],`,
    `  "context": "${lesson.communicativeNeed}",`,
    `  "exercises": [/* 4 exercises in order */],`,
    `  "homework": "",`,
    `  "materials": [],`,
    `  "teachingNotes": "[tutor notes in ${student.targetLanguage}]"`,
    `}`,
    ``,
    `RETURN ONLY VALID JSON, NO EXPLANATION.`,
  ]

  return lines.join('\n')
}
