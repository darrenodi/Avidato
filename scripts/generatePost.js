import fs from "fs";
import { GoogleGenerativeAI } from "@google/generative-ai";
import slugify from "slugify";
import { format } from "date-fns";

const genAI = new GoogleGenerativeAI(process.env.GOOGLE_API_KEY);

// Models to try in order of preference (from geminiFailover.ts)
const MODELS = [
  'gemini-2.5-pro',
  'gemini-2.5-flash',
  'gemini-2.5-flash-lite',
  'gemini-2.0-flash',
  'gemini-2.0-flash-lite',
];

// Topics for language learning blog
const TOPICS = [
  "Effective Strategies for Teaching English Grammar to Adult Learners",
  "How AI is Revolutionizing Language Education in 2025",
  "Creating Engaging ESL Lessons: Tips from Experienced Teachers",
  "The Role of Cultural Context in Language Learning",
  "Maximizing Student Engagement in Online ESL Classes",
  "Using Real-World Materials to Teach English",
  "The Science Behind Language Acquisition: What Teachers Need to Know",
  "Building Vocabulary Through Context and Repetition",
  "Assessment Strategies for ESL Students",
  "Incorporating Technology in the Language Classroom",
];

async function generateBlogPost() {
  try {
    // Select a random topic
    const topic = TOPICS[Math.floor(Math.random() * TOPICS.length)];
    console.log(`📝 Generating blog post about: "${topic}"`);

    // Try models in order until one works
    let content = null;
    let modelUsed = null;
    
    for (const modelName of MODELS) {
      try {
        console.log(`🤖 Trying to generate content with ${modelName}...`);
        const model = genAI.getGenerativeModel({ 
          model: modelName,
          generationConfig: {
            temperature: 0.8,
            topK: 40,
            topP: 0.95,
            maxOutputTokens: 2048,
          },
        });

        const prompt = `You are a professional education blogger writing for language teachers and tutors. 
Your tone is warm, knowledgeable, and practical. You provide actionable insights and real-world examples. 
Write in a conversational yet professional style. Use headings (##), bullet points, and clear structure.
Include practical tips, examples, and a conclusion. Make the content between 800-1200 words.

Write a comprehensive blog post about: "${topic}". 
Include:
- An engaging introduction
- 3-4 main sections with practical insights
- Real-world examples or scenarios
- Actionable tips teachers can implement
- A conclusion with key takeaways

Format using markdown with ## for headings.`;

        const result = await model.generateContent(prompt);
        content = result.response.text();
        
        if (content) {
          modelUsed = modelName;
          console.log(`✅ Successfully generated content with ${modelName}`);
          break;
        }
      } catch (error) {
        console.log(`❌ ${modelName} failed: ${error.message}`);
        // Continue to next model
        continue;
      }
    }

    if (!content) {
      throw new Error("All models failed to generate content. Please check your API quota.");
    }

    // Use placeholder image (Imagen API not yet implemented)
    console.log("🎨 Using placeholder image...");
    const imageUrl = "https://placehold.co/1792x1024/4F46E5/FFFFFF/png?text=Avidato+Blog";

    // Create slug and metadata
    const slug = slugify(topic, { lower: true, strict: true });
    const date = format(new Date(), "yyyy-MM-dd");
    
    // Extract first paragraph as description
    const firstParagraph = content.split('\n\n').find(p => p.length > 50) || content.substring(0, 200);
    const description = firstParagraph
      .replace(/^#+\s*/gm, '') // Remove markdown headings
      .replace(/\*\*/g, '') // Remove bold markers
      .split('\n')[0]
      .substring(0, 160);

    // Create MDX file with frontmatter
    const mdxContent = `---
title: "${topic}"
date: "${date}"
description: "${description}..."
slug: "${slug}"
image: "${imageUrl}"
author: "Avidato AI"
tags: ["Teaching", "ESL", "Education", "Language Learning"]
---

${content}

---

*This post was automatically generated by our AI content system powered by Google Gemini. The insights and tips are based on best practices in language education and teaching methodologies.*
`;

    // Save to content/blog directory
    const filePath = `./content/blog/${slug}.mdx`;
    fs.writeFileSync(filePath, mdxContent);

    console.log(`✅ Successfully created blog post!`);
    console.log(`📄 File: ${filePath}`);
    console.log(`🔗 Slug: ${slug}`);
    console.log(`🤖 Model used: ${modelUsed}`);
    
    return {
      success: true,
      slug,
      filePath,
      modelUsed,
    };
  } catch (error) {
    console.error("❌ Error generating blog post:", error);
    throw error;
  }
}

// Run the script
generateBlogPost()
  .then(() => {
    console.log("\n🎉 Blog post generation complete!");
    process.exit(0);
  })
  .catch((error) => {
    console.error("\n💥 Blog post generation failed:", error);
    process.exit(1);
  });

